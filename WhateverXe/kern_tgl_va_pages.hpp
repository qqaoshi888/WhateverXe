constexpr unsigned PageCount=sizeof(Pages)/sizeof(Pages[0]);
constexpr uint64_t AllPages=(1ULL<<PageCount)-1;
// Global site mask used by the opt-in subset selector. Bit order follows the
// page table: page 0 sites, then page 1 sites, and so on.
constexpr unsigned TotalSites=19;
constexpr uint32_t AllSiteMask=(1U<<TotalSites)-1;
inline unsigned siteBase(unsigned index) {
 unsigned base=0;
 for(unsigned i=0;i<index && i<PageCount;++i)base+=Pages[i].count;
 return base;
}
inline uint32_t pageSiteMask(unsigned index) {
 if(index>=PageCount)return 0;
 const auto base=siteBase(index);
 return ((1U<<Pages[index].count)-1)<<base;
}

template <typename PageT>
inline int matchPage(const void *data,size_t size,uint64_t offset,const PageT *pages,unsigned count) {
 if(!data || size!=4096 || !pages)return -1;
 for(unsigned i=0;i<count;++i) {
  const auto &p=pages[i];
  if(offset!=p.offset)continue;
  if(!hashMatches(data,size,p.sha256))return -1;
  for(unsigned j=0;j<p.count;++j) {
   uint32_t value;memcpy(&value,static_cast<const uint8_t *>(data)+p.sites[j].offset,4);
   if(value!=p.sites[j].expected)return -1;
  }
  return int(i);
 }
 return -1;
}
inline int match(const void *data,size_t size,uint64_t offset) {
 return matchPage(data,size,offset,Pages,PageCount);
}
template <typename PageT>
inline unsigned applyPage(void *data,const PageT &p) {
 if(!data)return 0;
 for(unsigned j=0;j<p.count;++j)memset(static_cast<uint8_t *>(data)+p.sites[j].offset,0,4);
 return p.count;
}
inline unsigned apply(void *data,unsigned index) {
 return index<PageCount ? applyPage(data,Pages[index]) : 0;
}
// Clear only the selected global sites; used by the subset selector and the
// probe mode. Returns the number of sites actually cleared.
inline unsigned applyMasked(void *data,unsigned index,uint32_t sites) {
 if(!data || index>=PageCount)return 0;
 const auto &p=Pages[index];
 const auto base=siteBase(index);
 unsigned cleared=0;
 for(unsigned j=0;j<p.count;++j)if(sites&(1U<<(base+j))) {
  memset(static_cast<uint8_t *>(data)+p.sites[j].offset,0,4);
  ++cleared;
 }
 return cleared;
}
